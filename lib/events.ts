import { supabase } from './supabase';

export type EventStatus = 'open' | 'closed';

export type EventRecord = {
  id: string;
  event_code: string;
  title: string;
  description: string | null;
  venue: string | null;
  start_time: string | null;
  end_time: string | null;
  status: EventStatus;
  created_by: string | null;
  created_at: string;
};

export type EventInput = {
  title: string;
  venue: string;
  description: string;
  start: Date;
  end: Date;
};

// What the person sees: combines the saved status with the time window.
export type EventPhase = 'upcoming' | 'ongoing' | 'ended' | 'closed';

export function getEventPhase(e: EventRecord, now = Date.now()): EventPhase {
  if (e.status === 'closed') return 'closed';
  if (e.start_time && now < new Date(e.start_time).getTime()) return 'upcoming';
  if (e.end_time && now > new Date(e.end_time).getTime()) return 'ended';
  return 'ongoing';
}

export const PHASE_LABEL: Record<EventPhase, string> = {
  upcoming: 'Upcoming',
  ongoing: 'Open',
  ended: 'Ended',
  closed: 'Closed',
};

const EVENT_COLUMNS =
  'id, event_code, title, description, venue, start_time, end_time, status, created_by, created_at';

export async function createEvent(
  input: EventInput
): Promise<{ event: EventRecord | null; error: string | null }> {
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) return { event: null, error: 'You are not signed in.' };

  // event_code is generated by the database.
  const { data, error } = await supabase
    .from('events')
    .insert({
      title: input.title.trim(),
      venue: input.venue.trim(),
      description: input.description.trim() || null,
      start_time: input.start.toISOString(),
      end_time: input.end.toISOString(),
      status: 'open',
      created_by: user.id,
    })
    .select(EVENT_COLUMNS)
    .single();

  if (error || !data) {
    return { event: null, error: error?.message ?? 'Could not create event.' };
  }
  return { event: data as EventRecord, error: null };
}

export async function updateEvent(
  id: string,
  input: EventInput
): Promise<{ event: EventRecord | null; error: string | null }> {
  const { data, error } = await supabase
    .from('events')
    .update({
      title: input.title.trim(),
      venue: input.venue.trim(),
      description: input.description.trim() || null,
      start_time: input.start.toISOString(),
      end_time: input.end.toISOString(),
    })
    .eq('id', id)
    .select(EVENT_COLUMNS)
    .maybeSingle();

  if (error) return { event: null, error: error.message };
  if (!data) {
    return { event: null, error: 'You are not allowed to edit this event.' };
  }
  return { event: data as EventRecord, error: null };
}

export async function setEventStatus(
  id: string,
  status: EventStatus
): Promise<{ error: string | null }> {
  const { data, error } = await supabase
    .from('events')
    .update({ status })
    .eq('id', id)
    .select('id')
    .maybeSingle();

  if (error) return { error: error.message };
  if (!data) return { error: 'You are not allowed to change this event.' };
  return { error: null };
}

// mineOnly: teachers only manage the events they created.
export async function listEvents(opts?: {
  mineOnly?: string;
}): Promise<{ events: EventRecord[]; error: string | null }> {
  let query = supabase
    .from('events')
    .select(EVENT_COLUMNS)
    .order('start_time', { ascending: false });

  if (opts?.mineOnly) query = query.eq('created_by', opts.mineOnly);

  const { data, error } = await query;
  if (error || !data) {
    return { events: [], error: error?.message ?? 'Could not load events.' };
  }
  return { events: data as EventRecord[], error: null };
}

export async function getEvent(id: string): Promise<EventRecord | null> {
  const { data, error } = await supabase
    .from('events')
    .select(EVENT_COLUMNS)
    .eq('id', id)
    .maybeSingle();

  if (error || !data) return null;
  return data as EventRecord;
}
