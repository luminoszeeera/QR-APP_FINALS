-- ---------------------------------------------------------------------
-- 2) HELPER: current user's role (SECURITY DEFINER avoids RLS recursion)
-- ---------------------------------------------------------------------
create or replace function public.get_my_role()
returns text
language sql stable security definer
set search_path = public
as $$
  select role from public.profiles where id = auth.uid()
$$;
revoke all on function public.get_my_role() from public, anon;
grant execute on function public.get_my_role() to authenticated;

-- ---------------------------------------------------------------------
-- 3) PROFILE CREATION ON SIGN-UP  (every new account is a student)
-- ---------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, full_name, role, id_number)
  values (
    new.id,
    new.email,
    nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''),
    'student',
    nullif(trim(new.raw_user_meta_data ->> 'id_number'), '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Role protection:
--  * new profile rows are ALWAYS 'student' (nobody can sign up as admin/teacher)
--  * only an administrator can change a role later
--    (the SQL editor / service role has no auth.uid(), so you can still
--     promote the first admin from the dashboard)
create or replace function public.profiles_role_guard()
returns trigger
language plpgsql security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    new.role := 'student';
  elsif tg_op = 'UPDATE' then
    if new.role is distinct from old.role
       and auth.uid() is not null
       and coalesce(public.get_my_role(), '') <> 'admin' then
      raise exception 'Only an administrator can change roles.';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_role_guard_trg on public.profiles;
create trigger profiles_role_guard_trg
  before insert or update on public.profiles
  for each row execute function public.profiles_role_guard();

-- ---------------------------------------------------------------------
-- 4) RECORD ATTENDANCE  (all attendance rules live here, on the server)
-- ---------------------------------------------------------------------
create or replace function public.record_attendance(p_event_code text)
returns jsonb
language plpgsql security definer
set search_path = public
as $$
declare
  v_uid   uuid := auth.uid();
  v_role  text;
  v_event public.events%rowtype;
  v_att   public.attendance%rowtype;
begin
  -- Unauthorized: not signed in
  if v_uid is null then
    return jsonb_build_object('ok', false, 'code', 'UNAUTHENTICATED',
      'message', 'Please sign in first.');
  end if;

  -- Unauthorized: only students may record attendance
  select role into v_role from public.profiles where id = v_uid;
  if v_role is distinct from 'student' then
    return jsonb_build_object('ok', false, 'code', 'FORBIDDEN',
      'message', 'Only student accounts can record attendance.');
  end if;

  -- Invalid QR: no event has this code
  select * into v_event from public.events
   where upper(event_code) = upper(trim(coalesce(p_event_code, '')));
  if not found then
    return jsonb_build_object('ok', false, 'code', 'INVALID_QR',
      'message', 'This QR code does not match any event.');
  end if;

  -- Closed event
  if v_event.status = 'closed' then
    return jsonb_build_object('ok', false, 'code', 'EVENT_CLOSED',
      'message', 'This event is closed. Attendance can no longer be recorded.',
      'eventTitle', v_event.title);
  end if;

  -- Time window
  if v_event.start_time is not null and now() < v_event.start_time then
    return jsonb_build_object('ok', false, 'code', 'NOT_STARTED',
      'message', 'This event has not started yet.',
      'eventTitle', v_event.title);
  end if;
  if v_event.end_time is not null and now() > v_event.end_time then
    return jsonb_build_object('ok', false, 'code', 'EVENT_ENDED',
      'message', 'This event has already ended.',
      'eventTitle', v_event.title);
  end if;

  -- Record it. The unique index (student_id, event_id) blocks duplicates.
  insert into public.attendance (student_id, event_id, status)
  values (v_uid, v_event.id, 'present')
  on conflict (student_id, event_id) do nothing
  returning * into v_att;

  if v_att.id is null then
    return jsonb_build_object('ok', false, 'code', 'DUPLICATE',
      'message', 'You already recorded attendance for this event.',
      'eventTitle', v_event.title);
  end if;

  return jsonb_build_object('ok', true,
    'eventTitle', v_event.title,
    'scannedAt',  v_att.scanned_at,
    'status',     v_att.status);
end;
$$;

revoke all on function public.record_attendance(text) from public, anon;
grant execute on function public.record_attendance(text) to authenticated;

-- ---------------------------------------------------------------------
-- 5) ROW LEVEL SECURITY
-- ---------------------------------------------------------------------
alter table public.profiles   enable row level security;
alter table public.events     enable row level security;
alter table public.attendance enable row level security;

-- Remove any older policies so only the ones below apply.
do $$
declare r record;
begin
  for r in
    select policyname, tablename from pg_policies
     where schemaname = 'public'
       and tablename in ('profiles', 'events', 'attendance')
  loop
    execute format('drop policy %I on public.%I', r.policyname, r.tablename);
  end loop;
end $$;

-- ---- profiles ----
-- See: yourself, everyone (admin), or students who attended YOUR events (teacher).
create policy profiles_select on public.profiles
  for select to authenticated
  using (
    id = auth.uid()
    or public.get_my_role() = 'admin'
    or exists (
      select 1
        from public.attendance a
        join public.events e on e.id = a.event_id
       where a.student_id = profiles.id
         and e.created_by = auth.uid()
    )
  );

-- Update: your own profile (role changes are blocked by the trigger above)...
create policy profiles_update_own on public.profiles
  for update to authenticated
  using (id = auth.uid())
  with check (id = auth.uid());

-- ...or any profile if you are an administrator.
create policy profiles_update_admin on public.profiles
  for update to authenticated
  using (public.get_my_role() = 'admin')
  with check (public.get_my_role() = 'admin');
-- (No INSERT/DELETE policy: profiles are created only by the sign-up trigger.)

-- ---- events ----
-- Everyone signed in can view events (students need "available events").
create policy events_select on public.events
  for select to authenticated
  using (true);

-- Only teachers/admins create events, and only as themselves.
create policy events_insert on public.events
  for insert to authenticated
  with check (
    public.get_my_role() in ('teacher', 'admin')
    and created_by = auth.uid()
  );

-- Edit / close: the teacher who owns the event, or an administrator.
create policy events_update on public.events
  for update to authenticated
  using (
    public.get_my_role() = 'admin'
    or (public.get_my_role() = 'teacher' and created_by = auth.uid())
  )
  with check (
    public.get_my_role() = 'admin'
    or (public.get_my_role() = 'teacher' and created_by = auth.uid())
  );

-- ---- attendance ----
-- Read: your own records, records of events you created, or everything (admin).
create policy attendance_select on public.attendance
  for select to authenticated
  using (
    student_id = auth.uid()
    or public.get_my_role() = 'admin'
    or exists (
      select 1 from public.events e
       where e.id = attendance.event_id
         and e.created_by = auth.uid()
    )
  );

-- Correct / remove records: administrators only.
create policy attendance_update_admin on public.attendance
  for update to authenticated
  using (public.get_my_role() = 'admin')
  with check (public.get_my_role() = 'admin');

create policy attendance_delete_admin on public.attendance
  for delete to authenticated
  using (public.get_my_role() = 'admin');

-- NOTE: there is deliberately NO insert policy on attendance.
-- Students can only record attendance through record_attendance(), which
-- applies every validation rule on the server.

