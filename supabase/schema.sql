-- Profiles: one row per auth user (1 user -> 1 profile).
create table if not exists public.profiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  email      text,
  full_name  text,
  role       text not null default 'student',
  id_number  text,
  created_at timestamptz not null default now()
);
alter table public.profiles add column if not exists id_number  text;
alter table public.profiles add column if not exists created_at timestamptz not null default now();

do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'profiles_role_check') then
    alter table public.profiles
      add constraint profiles_role_check check (role in ('student', 'teacher', 'admin'));
  end if;
end $$;

-- Event codes are generated by the database (what the QR code contains).
create or replace function public.gen_event_code()
returns text language sql volatile as $$
  select 'EVT-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 8));
$$;

-- Events: one teacher/admin (profiles) -> many events.
create table if not exists public.events (
  id          uuid primary key default gen_random_uuid(),
  event_code  text not null unique default public.gen_event_code(),
  title       text not null,
  description text,
  venue       text,
  start_time  timestamptz,
  end_time    timestamptz,
  status      text not null default 'open',
  created_by  uuid references public.profiles(id) on delete set null default auth.uid(),
  created_at  timestamptz not null default now()
);
alter table public.events add column if not exists description text;
alter table public.events add column if not exists venue       text;
alter table public.events add column if not exists status      text not null default 'open';
alter table public.events alter column event_code set default public.gen_event_code();
alter table public.events alter column created_by set default auth.uid();

do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'events_status_check') then
    alter table public.events
      add constraint events_status_check check (status in ('open', 'closed'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'events_time_check') then
    alter table public.events
      add constraint events_time_check
      check (start_time is null or end_time is null or end_time > start_time) not valid;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'events_title_length_check') then
    alter table public.events
      add constraint events_title_length_check
      check (char_length(title) between 3 and 100) not valid;
  end if;
end $$;

-- Attendance: one student (profiles) + one event (events) -> one record.
create table if not exists public.attendance (
  id         uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.profiles(id) on delete cascade,
  event_id   uuid not null references public.events(id)   on delete cascade,
  status     text not null default 'present',
  scanned_at timestamptz not null default now()
);
alter table public.attendance add column if not exists status     text not null default 'present';
alter table public.attendance add column if not exists scanned_at timestamptz not null default now();

do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'attendance_status_check') then
    alter table public.attendance
      add constraint attendance_status_check check (status in ('present', 'excused', 'absent'));
  end if;
end $$;

-- Duplicate attendance prevention: a student can only have ONE record per event.
-- (If this fails, you have old duplicate rows: delete the extra ones first.)
create unique index if not exists attendance_student_event_uidx
  on public.attendance (student_id, event_id);

